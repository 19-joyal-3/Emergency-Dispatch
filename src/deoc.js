export function getDeocByDistrict(id) {
  return KERALA_DEOC_DIRECTORY.find(d => d.id === id) || null;
}

export function searchDeoc(term) {
  if (!term) return KERALA_DEOC_DIRECTORY;
  const q = term.toLowerCase().trim();
  return KERALA_DEOC_DIRECTORY.filter(d => 
    d.name.toLowerCase().includes(q) ||
    d.malayalam.includes(q) ||
    d.primaryHazards.some(h => h.toLowerCase().includes(q))
  );
}
